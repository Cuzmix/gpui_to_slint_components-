#!/usr/bin/env python3
"""Generates ui/icons/icons.slint: one `@image-url` property per Lucide SVG in ui/icons,
and `Icons.all`, every icon with its name in the order of ely-core's `IconName::ALL`.

Usage: gen_icons.py <ui/icons dir> <ely-core/src/primitives/icon/names.rs>
"""
import os, re, sys
d, names_rs = sys.argv[1], sys.argv[2]
files = set(f[:-4] for f in os.listdir(d) if f.endswith('.svg'))
order = re.findall(r'^\s*\w+\s*=>\s*"([^"]+)",', open(names_rs).read(), re.M)
assert set(order) == files, (set(order) ^ files)
out = ['// Generated by scripts/gen_icons.py from the Lucide 1.48.0 SVGs (ISC) that Ely bundles.\n',
       '// Do not edit by hand; rerun the script.\n\n',
       '// One bundled icon and its Lucide name.\n',
       'export struct IconEntry {\n    name: string,\n    image: image,\n}\n\n',
       '// Every bundled icon, by its Lucide name: `Icons.chevron-down`.\n',
       'export global Icons {\n']
for n in sorted(files):
    out.append(f'    out property <image> {n}: @image-url("{n}.svg");\n')
out.append('\n    // Every bundled icon, in the order of ely-core\'s `IconName::ALL`.\n')
out.append('    out property <[IconEntry]> all: [\n')
for n in order:
    out.append(f'        {{ name: "{n}", image: @image-url("{n}.svg") }},\n')
out.append('    ];\n}\n')
open(os.path.join(d, 'icons.slint'), 'w').write(''.join(out))
print(len(order))
