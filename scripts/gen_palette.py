#!/usr/bin/env python3
"""Generates ui/theme/palette.slint from the GPUI source's theme/palette.rs.

Usage: gen_palette.py <path to ely-core/src/theme/palette.rs> <output .slint>
Every hex value comes from the source; nothing is typed by hand.
"""
import re, sys

src = open(sys.argv[1]).read()

def fields(block_name):
    m = re.search(r'mixable!\(\s*///[^\n]*\n\s*' + block_name + r' \{(.*?)\n\s*\}\n\);', src, re.S)
    body = m.group(1)
    colors_part, _, rest = body.partition(';')
    colors = re.findall(r'^\s*([a-z_]+),\s*$', colors_part, re.M)
    extra = re.findall(r'^\s*([a-z_]+): ([^,]+),\s*$', rest, re.M)
    docs = {}
    for doc, name in re.findall(r'///\s*([^\n]*)\n\s*([a-z_]+)[,:]', body):
        docs[name] = doc
    return colors, extra, docs

pal_colors, pal_extra, pal_docs = fields('Palette')
syn_colors, _, syn_docs = fields('Syntax')

def kebab(n): return n.replace('_', '-')

def color_expr(v):
    v = v.strip()
    m = re.fullmatch(r'c\(0x([0-9a-f]{6})\)', v)
    if m: return '#' + m.group(1)
    m = re.fullmatch(r'rgba\(0x([0-9a-f]{8})\)\.into\(\)', v)
    if m: return '#' + m.group(1)
    raise ValueError(v)

def hexlist(s):
    return ['#' + h for h in re.findall(r'0x([0-9a-f]{6})', s)]

def parse_palette(fn):
    m = re.search(r'pub fn ' + fn + r'\(high_contrast: bool\) -> Self \{(.*?)\n    \}\n', src, re.S)
    body = m.group(1)
    base_m = re.search(r'let mut palette = Self \{(.*?)\n        \};', body, re.S)
    base_body = base_m.group(1)
    vals = {}
    for name, v in re.findall(r'^\s{12}([a-z_]+): ((?:c|rgba)\(0x[0-9a-f]+\)(?:\.into\(\))?),', base_body, re.M):
        vals[name] = color_expr(v)
    chart = hexlist(re.search(r'chart: c8\(\[(.*?)\]\)', base_body, re.S).group(1))
    ansi = hexlist(re.search(r'ansi: c8\(\[(.*?)\]\)', base_body, re.S).group(1))
    syn_body = re.search(r'syntax: Syntax \{(.*?)\}', base_body, re.S).group(1)
    syn = {n: color_expr(v) for n, v in re.findall(r'([a-z_]+): (c\(0x[0-9a-f]+\))', syn_body)}
    hc = {}
    hc_body = re.search(r'if high_contrast \{(.*?)\}', body, re.S).group(1)
    for name, v in re.findall(r'palette\.([a-z_]+) = ([^;]+);', hc_body):
        hc[name] = ('@' + v.split('.')[1]) if v.startswith('palette.') else color_expr(v)
    return vals, chart, ansi, syn, hc

def cb(mode):
    m = re.search(r'Mode::' + mode + r' => c8\(\[(.*?)\]\)', src, re.S)
    return hexlist(m.group(1))

out = []
w = out.append
w('// Generated by scripts/gen_palette.py from Ely-GPUI-Components ely-core/src/theme/palette.rs.\n')
w('// Do not edit by hand; rerun the script.\n\n')
w('// Code token colors.\nexport struct Syntax {\n')
for n in syn_colors: w(f'    // {syn_docs.get(n, "")}\n    {kebab(n)}: color,\n')
w('}\n\n')
w('// Semantic colors. Components read these, never literals.\nexport struct Palette {\n')
for n in pal_colors: w(f'    // {pal_docs.get(n, "")}\n    {kebab(n)}: color,\n')
w('    // The chart\'s eight hues, named by Theme.hue-names.\n    chart: [color],\n')
w('    // The terminal\'s sixteen colors.\n    ansi: [color],\n')
w('    // Code token colors.\n    syntax: Syntax,\n}\n\n')

def literal(vals, chart, ansi, syn, hc, ind, chart_override=None):
    v = dict(vals)
    for k, x in hc.items():
        v[k] = v[x[1:]] if x.startswith('@') else x
    s = '{\n'
    for n in pal_colors: s += f'{ind}    {kebab(n)}: {v[n]},\n'
    s += f'{ind}    chart: [{", ".join(chart_override or chart)}],\n'
    s += f'{ind}    ansi: [{", ".join(ansi)}],\n'
    s += f'{ind}    syntax: {{ ' + ', '.join(f'{kebab(n)}: {syn[n]}' for n in syn_colors) + ' },\n'
    s += ind + '}'
    return s

L = parse_palette('light'); D = parse_palette('dark')
w('// Ely\'s built-in palettes, and the blend used by the light/dark fade.\nexport global Palettes {\n')
w('    // Ely\'s light palette.\n    out property <Palette> light: ' + literal(*L[:4], {}, '    ') + ';\n')
w('    // Ely\'s light palette with high contrast.\n    out property <Palette> light-high-contrast: ' + literal(*L, '    ') + ';\n')
w('    // Ely\'s dark palette. Soft greys, never black: the base is #252525.\n    out property <Palette> dark: ' + literal(*D[:4], {}, '    ') + ';\n')
w('    // Ely\'s dark palette with high contrast.\n    out property <Palette> dark-high-contrast: ' + literal(*D, '    ') + ';\n')
w('    // Chart hues each 3:1 on the light page that stay apart for protanopia, deuteranopia and tritanopia.\n')
w(f'    out property <[color]> color-blind-chart-light: [{", ".join(cb("Light"))}];\n')
w('    // The same, for the dark page.\n')
w(f'    out property <[color]> color-blind-chart-dark: [{", ".join(cb("Dark"))}];\n\n')
w('''    // The blend a share `t` of the way from `a` to `b`, mixed per channel in sRGB like GPUI's `Mix`.
    public pure function mix(a: color, b: color, t: float) -> color {
        if (t <= 0) {
            return a;
        }
        if (t >= 1) {
            return b;
        }
        rgba(a.red + (b.red - a.red) * t, a.green + (b.green - a.green) * t, a.blue + (b.blue - a.blue) * t, (a.alpha + (b.alpha - a.alpha) * t) / 255)
    }

    // Every color of `a` blended a share `t` of the way to `b`.
    public pure function mix-palette(a: Palette, b: Palette, t: float) -> Palette {
        {
''')
for n in pal_colors: w(f'            {kebab(n)}: mix(a.{kebab(n)}, b.{kebab(n)}, t),\n')
w('            chart: [' + ', '.join(f'mix(a.chart[{i}], b.chart[{i}], t)' for i in range(8)) + '],\n')
w('            ansi: [' + ', '.join(f'mix(a.ansi[{i}], b.ansi[{i}], t)' for i in range(16)) + '],\n')
w('            syntax: { ' + ', '.join(f'{kebab(n)}: mix(a.syntax.{kebab(n)}, b.syntax.{kebab(n)}, t)' for n in syn_colors) + ' },\n')
w('        }\n    }\n\n')
w('    // `p` with its chart hues swapped for `chart`.\n    public pure function with-chart(p: Palette, chart: [color]) -> Palette {\n        {\n')
for n in pal_colors: w(f'            {kebab(n)}: p.{kebab(n)},\n')
w('            chart: chart,\n            ansi: p.ansi,\n            syntax: p.syntax,\n        }\n    }\n}\n')
open(sys.argv[2], 'w').write(''.join(out))
print('colors', len(pal_colors), 'syntax', len(syn_colors), 'hc', L[4], D[4])
